import { describe, expect, it } from 'vitest';
import { DEFAULT_RAIL_PITCH_MM } from '../src/layout/limits';
import { createPanel } from '../src/layout/panel';
import { nextPlacementId, type Panel, type Placement } from '../src/layout/placement';
import { Camera } from '../src/view/Camera';
import {
  FRAME_PADDING,
  ROW_MARGIN,
  frameRect,
  labelRoom,
  moduleRect,
  placementAt,
  railAtPoint,
  railCenterY,
  railRect,
  snapToSlot,
} from '../src/view/geometry';
import { History } from '../src/view/history';

const placement = (id: string, rail: number, slot: number): Placement => ({
  id,
  module: { libraryId: 'lib', moduleId: 'm' },
  rail,
  slot,
});

const panel = (...placements: Placement[]): Panel => ({ ...createPanel([10, 6]), placements });

const at = (unit: number, rail: number) => ({
  x: FRAME_PADDING + unit * 17.5,
  y: FRAME_PADDING + ROW_MARGIN + rail * DEFAULT_RAIL_PITCH_MM,
});

describe('snapToSlot', () => {
  it('puts the grabbed point of the module under the pointer', () => {
    expect(snapToSlot(panel(), at(5.2, 0), 2, 1)).toEqual({ rail: 0, slot: 4 });
  });

  it('picks the rail row under the pointer', () => {
    expect(snapToSlot(panel(), at(3, 1), 1, 0)).toEqual({ rail: 1, slot: 3 });
  });

  it('clamps into the rail at both ends', () => {
    expect(snapToSlot(panel(), at(-4, 0), 2, 1)).toEqual({ rail: 0, slot: 0 });
    expect(snapToSlot(panel(), at(40, 1), 2, 1)).toEqual({ rail: 1, slot: 4 });
  });

  it('returns null above the first row and below the last', () => {
    expect(snapToSlot(panel(), { x: 100, y: 5 }, 1, 0)).toBeNull();
    expect(snapToSlot(panel(), at(3, 2), 1, 0)).toBeNull();
  });

  it('never returns a negative slot for a module wider than the rail', () => {
    expect(snapToSlot(panel(), at(2, 1), 8, 0)?.slot).toBe(0);
  });
});

describe('placementAt', () => {
  const widthOf = () => 2;
  const target = panel(placement('a', 0, 3), placement('b', 1, 0));

  it('finds the module under the point', () => {
    const rect = moduleRect(target, 0, 3, 2);
    expect(placementAt(target, widthOf, { x: rect.x + 5, y: rect.y + 5 })?.id).toBe('a');
  });

  it('returns undefined on empty rail space', () => {
    expect(placementAt(target, widthOf, at(8, 0))).toBeUndefined();
  });
});

describe('nextPlacementId', () => {
  it('starts at p1 and continues after the highest id', () => {
    expect(nextPlacementId(panel())).toBe('p1');
    expect(nextPlacementId(panel(placement('p1', 0, 0), placement('p7', 0, 2)))).toBe('p8');
  });

  it('ignores ids that are not generated by it', () => {
    expect(nextPlacementId(panel(placement('custom', 0, 0)))).toBe('p1');
  });
});

describe('History', () => {
  it('undoes and redoes commits', () => {
    const history = new History(0);
    history.commit(1);
    history.commit(2);
    expect(history.undo()).toBe(true);
    expect(history.current).toBe(1);
    expect(history.redo()).toBe(true);
    expect(history.current).toBe(2);
  });

  it('reports nothing to undo or redo at the ends', () => {
    const history = new History(0);
    expect(history.undo()).toBe(false);
    expect(history.redo()).toBe(false);
  });

  it('drops the redo branch on a new commit', () => {
    const history = new History(0);
    history.commit(1);
    history.undo();
    history.commit(5);
    expect(history.canRedo).toBe(false);
    expect(history.current).toBe(5);
  });

  it('keeps at most `limit` undo steps', () => {
    const history = new History(0, 2);
    [1, 2, 3].forEach((n) => history.commit(n));
    history.undo();
    history.undo();
    expect(history.undo()).toBe(false);
    expect(history.current).toBe(1);
  });
});

describe('Camera', () => {
  it('keeps the world point under the cursor fixed while zooming', () => {
    const camera = new Camera();
    const cursor = { x: 300, y: 200 };
    const before = camera.screenToWorld(cursor, 800, 600);
    camera.zoomAt(cursor, 2, 800, 600);
    const after = camera.screenToWorld(cursor, 800, 600);
    expect(after.x).toBeCloseTo(before.x);
    expect(after.y).toBeCloseTo(before.y);
  });

  it('round-trips world and screen coordinates', () => {
    const camera = new Camera();
    camera.x = 50;
    camera.scale = 1.5;
    const screen = camera.worldToScreen({ x: 10, y: 20 }, 800, 600);
    expect(camera.screenToWorld(screen, 800, 600)).toEqual({ x: 10, y: 20 });
  });
});

describe('panel geometry with custom pitches', () => {
  const uneven = (): Panel => ({ ...createPanel([10, 10, 10]), railPitchesMm: [200, 120] });

  it('places each rail centre after the pitches above it', () => {
    const p = uneven();
    const first = FRAME_PADDING + ROW_MARGIN;
    expect([0, 1, 2].map((rail) => railCenterY(p, rail))).toEqual([first, first + 200, first + 320]);
  });

  it('centres modules and rails on the same line', () => {
    const p = uneven();
    const module = moduleRect(p, 1, 0, 1);
    const rail = railRect(p, 1);
    expect(module.y + module.height / 2).toBe(rail.y + rail.height / 2);
  });

  it('grows the frame by exactly the added spacing', () => {
    const base = frameRect(createPanel([10, 10, 10])).height;
    expect(frameRect(uneven()).height).toBe(base + (200 - DEFAULT_RAIL_PITCH_MM) + (120 - DEFAULT_RAIL_PITCH_MM));
  });

  it('snaps to the nearest rail and ignores the empty gap between rows', () => {
    const p = uneven();
    const x = FRAME_PADDING + 50;
    expect(snapToSlot(p, { x, y: railCenterY(p, 1) + 30 }, 1, 0)?.rail).toBe(1);
    expect(snapToSlot(p, { x, y: railCenterY(p, 2) - 30 }, 1, 0)?.rail).toBe(2);
    expect(snapToSlot(p, { x, y: railCenterY(p, 0) + 100 }, 1, 0)).toBeNull();
  });

  it('keeps the default frame height of the single-pitch layout', () => {
    expect(frameRect(createPanel([10, 10])).height).toBe(2 * FRAME_PADDING + 2 * ROW_MARGIN + DEFAULT_RAIL_PITCH_MM);
    expect(frameRect(createPanel([])).height).toBe(FRAME_PADDING);
  });
});

describe('labelRoom', () => {
  it('stops above the combs that overhang the next row', () => {
    const panel = createPanel([10, 10]);
    expect(labelRoom(panel, 0)).toBe(DEFAULT_RAIL_PITCH_MM - 90 - 10 - 8);
  });

  it('runs to the end of the frame under the last row', () => {
    const panel = createPanel([10, 10]);
    expect(labelRoom(panel, 1)).toBe(ROW_MARGIN + FRAME_PADDING - 45 - 8);
  });

  it('grows with the spacing between rows', () => {
    const wide = { ...createPanel([10, 10]), railPitchesMm: [250] };
    expect(labelRoom(wide, 0)).toBe(labelRoom(createPanel([10, 10]), 0) + 100);
  });

  it('never goes negative', () => {
    const tight = { ...createPanel([10, 10]), railPitchesMm: [90] };
    expect(labelRoom(tight, 0)).toBe(0);
  });
});

describe('railAtPoint', () => {
  const panel = () => ({ ...createPanel([10, 6]), railPitchesMm: [200] });

  it('finds the row whose rail bar is under the point', () => {
    const p = panel();
    expect(railAtPoint(p, { x: FRAME_PADDING + 40, y: railCenterY(p, 0) })).toBe(0);
    expect(railAtPoint(p, { x: FRAME_PADDING + 40, y: railCenterY(p, 1) + 10 })).toBe(1);
  });

  it('stops at the end of a shorter rail and at the edges of the bar', () => {
    const p = panel();
    expect(railAtPoint(p, { x: FRAME_PADDING + 6 * 17.5 + 5, y: railCenterY(p, 1) })).toBeUndefined();
    expect(railAtPoint(p, { x: FRAME_PADDING + 6 * 17.5 + 5, y: railCenterY(p, 0) })).toBe(0);
    expect(railAtPoint(p, { x: FRAME_PADDING + 20, y: railCenterY(p, 0) + 30 })).toBeUndefined();
  });

  it('finds nothing on a panel without rails or away from them', () => {
    expect(railAtPoint(createPanel([]), { x: 50, y: 50 })).toBeUndefined();
    expect(railAtPoint(panel(), { x: 5000, y: 5000 })).toBeUndefined();
  });
});

describe('snapToSlot against neighbours and with fractional widths', () => {
  const relay = 22.5 / 17.5;

  it('draws a module up against the end of its neighbour when it comes within about 5 mm', () => {
    const neighbour = [{ rail: 0, slot: 2, widthUnits: relay }];
    const edge = 2 + relay;
    expect(snapToSlot(panel(), at(edge + 0.2, 0), 1, 0, neighbour)).toEqual({ rail: 0, slot: Math.round(edge * 1e4) / 1e4 });
    expect(snapToSlot(panel(), at(edge - 0.25, 0), 1, 0, neighbour)?.slot).toBeCloseTo(edge, 3);
  });

  it('draws a module up against the front of its neighbour, which puts its own end on that edge', () => {
    const neighbour = [{ rail: 0, slot: 5, widthUnits: 2 }];
    expect(snapToSlot(panel(), at(3.9, 0), relay, 0, neighbour)?.slot).toBeCloseTo(5 - relay, 3);
  });

  it('keeps to whole units when everything on the rail is whole, as before', () => {
    const neighbour = [{ rail: 0, slot: 2, widthUnits: 2 }];
    expect(snapToSlot(panel(), at(4.4, 0), 1, 0, neighbour)).toEqual({ rail: 0, slot: 4 });
    expect(snapToSlot(panel(), at(7.35, 0), 1, 0, neighbour)).toEqual({ rail: 0, slot: 7 });
  });

  it('puts a module that is not a whole number of units on a half-millimetre grid when no edge is near', () => {
    const slot = snapToSlot(panel(), at(7.34, 0), relay, 0)!.slot;
    expect(slot * 17.5 * 2).toBeCloseTo(Math.round(slot * 17.5 * 2), 1);
    expect(Math.abs(slot - 7.34)).toBeLessThan(0.02);
  });

  it('ignores neighbours on another rail and keeps the module inside its own rail', () => {
    const elsewhere = [{ rail: 1, slot: 2, widthUnits: 2 }];
    expect(snapToSlot(panel(), at(4.2, 0), 1, 0, elsewhere)).toEqual({ rail: 0, slot: 4 });
    expect(snapToSlot(panel(), at(100, 0), relay, 0)?.slot).toBeCloseTo(10 - relay, 3);
  });
});
